package main.java.backend.model;

import main.java.enums.data.ReportType;

import java.time.LocalDate;

public class Report {

    private final String reportID;
    private final String reportDocNo;
    private final LocalDate reportCreationDate;
    private final ReportType reportType;
    private StaffAccount managerAccount;

    public Report(String reportID, String reportDocNo, LocalDate reportCreationDate, ReportType reportType,
                  StaffAccount managerAccount) {
        this.reportID = reportID;
        this.reportDocNo = reportDocNo;
        this.reportCreationDate = reportCreationDate;
        this.reportType = reportType;
        this.managerAccount = managerAccount;
    }

    public String getReportID() {
        return reportID;
    }

    public String getReportDocNo() {
        return reportDocNo;
    }

    public LocalDate getReportCreationDate() {
        return reportCreationDate;
    }

    public ReportType getReportType() {
        return reportType;
    }

    public StaffAccount getManagerAccount() {
        return managerAccount;
    }

    public void setManagerAccount(StaffAccount managerAccount) {
        this.managerAccount = managerAccount;
    }

    /**
     * Return a human-readable string representation of the object.
     * Used for logging, debugging, testing, or printing overall information.
     */
    @Override
    public String toString() {
        return "Report ID: " + reportID +
                "\nReport No: " + reportDocNo +
                "\nReport Creation Date: " + reportCreationDate +
                "\nReport Type: " + reportType.getReportType() +
                "\nGenerated By: " +
                (managerAccount != null ? managerAccount.getFirstName() + " " + managerAccount.getLastName()
                        : "(manager unavailable/deleted)");
    }
}
